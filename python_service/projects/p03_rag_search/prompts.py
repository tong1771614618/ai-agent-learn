"""
==========================================================================
  AI 知识点: RAG Prompt 设计（上下文注入）
==========================================================================

  【概念 6: Context Injection（上下文注入）】

  RAG 的核心 Prompt 技巧：把检索到的知识"注入"到 System Prompt 中，
  让 LLM 基于这些上下文回答问题。

  对比项目 1 和 2 的 Prompt：
  ┌──────────────────────────────────────────────────────────────┐
  │ 项目      │ System Prompt 构成                               │
  ├───────────┼──────────────────────────────────────────────────┤
  │ 项目 1    │ 角色设定 + 输出格式要求                          │
  │ 项目 2    │ 角色设定 + 可用工具描述                          │
  │ 项目 3    │ 角色设定 + 【检索到的知识】+ 回答规则            │
  └───────────┴──────────────────────────────────────────────────┘

  关键规则：
  1. "只根据提供的知识回答" — 防止 LLM 胡编乱造（幻觉）
  2. "如果知识不足以回答，明确说明" — 让 LLM 承认不知道
  3. "引用具体来源" — 让回答可溯源

  上游：ai_service.py 把检索到的 chunks 填入 {context} 占位符
  下游：填入后的完整 prompt 作为 system message 发给 LLM
==========================================================================
"""

SYSTEM_PROMPT = """你是 DevShop 电商平台的 AI 客服助手。你的任务是根据提供的知识库内容，准确回答用户的购物相关问题。

## 回答规则
1. 只根据提供的【知识库】内容回答，不要编造知识库中没有的信息
2. 如果知识库中没有相关内容，明确告诉用户"知识库中暂无相关内容"
3. 回答时引用具体来源（如"根据平台政策..."、"根据品类知识..."）
4. 可以适当组织和扩展知识，但核心内容必须来自知识库
5. 如果问题涉及多个知识点，分点回答
6. 涉及金额、时效等具体数字时，务必准确引用知识库中的数值

## 知识库内容

{context}
"""

